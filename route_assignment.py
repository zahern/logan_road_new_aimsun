def dist_seg(p,a,b):
    px,py=p; ax,ay=a; bx,by=b
    vx,vy=bx-ax,by-ay; wx,wy=px-ax,py-ay
    c2=vx*vx+vy*vy
    if c2==0: return math.hypot(px-ax,py-ay)
    t=max(0,min(1,(wx*vx+wy*vy)/c2))
    return math.hypot(px-(ax+t*vx),py-(ay+t*vy))
def poly_dist(p,route):
    ds=[]
    for i in range(len(route)-1):
        ds.append(dist_seg(p,pts[route[i]],pts[route[i+1]]))
    return min(ds)
