"""build_kg_channel_sections.py -- KG SCATS channel -> Aimsun SECTION map.

The KG model has physical 11137xxx loops ONLY on the arterial approaches
(ART_CALL) and departures (ART_PRES); there are NO cross-street / turn-bay /
slip loops. So the SIDE / RT_BAY / SLIP channels cannot be wired to physical
detectors -- but the model DOES contain a SECTION for every approach, and the
virtual inductive loop (engine._virtual_loop_flow_vph) monitors ANY section. So
this resolves each KG junction's SIDE / RT_BAY / SLIP channels to SECTION IDs:

  ART_CALL  sections of the junction's UpDetList loops (+ config MainSections)
  SIDE      config SideSections (cross-street approach sections)
  RT_BAY    entry sections (from turnings into the node) that are NOT arterial
            or side and serve a SINGLE downstream section (a pure turn bay)
  SLIP      entry sections whose name carries "slip"

Writes kg/scats_channel_sections.py (channel -> [section_id, ...]).

Run locally on Windows:  python build_kg_channel_sections.py
"""
import importlib.util
import json
import os
import re
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
KG_DIR = os.path.join(HERE, "kg")
DUMP = os.path.join(os.path.dirname(HERE), "sumo_bridge", "kg_aimsun_dump.json")
OUT = os.path.join(KG_DIR, "scats_channel_sections.py")


def _load_cfg():
    spec = importlib.util.spec_from_file_location(
        "kg_int_cfgs", os.path.join(KG_DIR, "intersection_configs.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m.INTERSECTIONS_CONFIG


def _load_dump():
    d = json.load(open(DUMP, encoding="utf-8"))
    det2sec = {int(x["id"]): int(x["section"]) for x in d["detectors"]}
    turns = [t for t in (d["turnings"].values()
                         if isinstance(d["turnings"], dict) else d["turnings"])]
    entry = defaultdict(set)          # node -> {from_section}
    dests = defaultdict(lambda: defaultdict(set))   # node -> from_sec -> {to_sec}
    for t in turns:
        nid = int(t.get("node", 0) or 0)
        fs = int(t.get("from_section", 0) or 0)
        ts = int(t.get("to_section", 0) or 0)
        if nid and fs:
            entry[nid].add(fs)
            if ts:
                dests[nid][fs].add(ts)
    sec_name = {int(k): (v.get("name") or "") for k, v in d["sections"].items()}
    return det2sec, entry, dests, sec_name


def build():
    cfg = _load_cfg()
    det2sec, entry, dests, sec_name = _load_dump()
    out = {}
    report = []
    for jid, c in sorted(cfg.items()):
        jid = int(jid)
        art = set()
        for g in (c.get("UpDetList") or []):
            for dd in (g or []):
                s = det2sec.get(int(dd))
                if s:
                    art.add(int(s))
        art |= {int(s) for s in (c.get("MainSections") or [])}
        side = {int(s) for s in (c.get("SideSections") or [])}
        ent = {int(s) for s in entry.get(jid, set())}
        rt, slip = set(), set()
        for s in ent - art - side:
            nm = (sec_name.get(s, "") or "").lower()
            dset = dests.get(jid, {}).get(s, set())
            if "slip" in nm:
                slip.add(s)
            elif len(dset) == 1:
                rt.add(s)                 # single-destination entry = pure turn bay
        out[jid] = {"ART": sorted(art), "SIDE": sorted(side),
                    "RT_BAY": sorted(rt), "SLIP": sorted(slip),
                    "UNMONITORED": sorted(ent - art - side - rt - slip)}
        report.append((jid, len(art), len(side), len(rt), len(slip),
                       len(out[jid]["UNMONITORED"])))

    lines = [
        '"""kg/scats_channel_sections.py -- GENERATED by ',
        'build_kg_channel_sections.py. Do not edit by hand.\n',
        "SCATS channel -> Aimsun SECTION ids for the KG corridor. The KG model has",
        "NO physical side/turn/slip loops, so these channels are monitored by the",
        "VIRTUAL inductive loop (engine._virtual_loop_flow_vph, any section).\n",
        '"""',
        "",
        "SCATS_CHANNEL_SECTIONS = {",
    ]
    for jid in sorted(out):
        e = out[jid]
        lines.append(
            '    %d: {"ART": %s, "SIDE": %s, "RT_BAY": %s, "SLIP": %s},'
            % (jid, e["ART"], e["SIDE"], e["RT_BAY"], e["SLIP"]))
    lines.append("}")
    lines.append("")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    print("=== KG SCATS channel -> section map ===")
    print("%-9s %5s %6s %7s %6s %12s" %
          ("junction", "ART", "SIDE", "RT_BAY", "SLIP", "UNMONITORED"))
    for r in report:
        print("%-9s %5d %6d %7d %6d %12d" % r)
    print("\n[written] %s" % OUT)
    return out


if __name__ == "__main__":
    build()
