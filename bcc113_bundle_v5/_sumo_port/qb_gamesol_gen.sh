#!/bin/bash
# qb_gamesol_gen.sh -- submit the SUMO half of the GAME_SOLUTION comparison.
#
# Run this ON AQUARIUS (it only writes files and calls qsub):
#   bash /home/ahernz/tsp/sumo_hpc/qb_gamesol_gen.sh          # QUICK: 4 arms, seed 300
#   FULL=1 bash /home/ahernz/tsp/sumo_hpc/qb_gamesol_gen.sh   # 10 arms x 3 seeds
#   DRY=1  bash /home/ahernz/tsp/sumo_hpc/qb_gamesol_gen.sh   # write + print, no qsub
#   ARMS="CHAMP_ADAPTIVE_DSW_GAME_COOP" SEEDS="300,400" bash ...
#
# WHY THIS REPLACES `qsub -v ...` (see gen_champ9_job.sh for the original finding):
# this PBS honours ONLY the last -v and silently discards earlier ones. Verified:
#   qsub -v A=1 -v B=2 -v C=3 -v D=4 p.pbs  =>  A=[] B=[] C=[] D=[4]
# Jobs 27677851/52/54/55 died in 17 s on exactly that ("ARM: need ARM=..."),
# and the comma form was never proven either. So this generator writes a
# self-contained PBS file per (arm, seed) with the values hard-coded: there is
# no -v, no comma parsing and no environment inheritance to lose them.
#
# Corridor is baked as well, because a dropped CORR falls back to a default and
# would silently simulate the wrong network instead of failing.
#
# Results: $BASE/parts/gamesol_<SHORT>_eval<SEED>.csv (one file per run, so two
# jobs can never clobber each other's rows).
set -u
BASE="${BASE:-/home/ahernz/tsp/sumo_hpc}"
RPID="${RPID:-FPAXJW8067}"
CORR="${CORR:-kg}"
END="${END:-4500}"
GEN="${GEN:-$BASE/jobs}"
mkdir -p "$GEN" || exit 1

ALL_ARMS=(
  CHAMP_ADAPTIVE_DSW_GAME_COOP
  CHAMP_ADAPTIVE_DSW_GAME_SOL_NASH
  CHAMP_ADAPTIVE_DSW_GAME_SOL_UTIL
  CHAMP_ADAPTIVE_DSW_GAME_SOL_NWELF
  CHAMP_ADAPTIVE_DSW_GAME_SOL_EGAL
  CHAMP_ADAPTIVE_DSW_GAME_SOL_KS
  CHAMP_ADAPTIVE_DSW_GAME_SOL_STACKBUS
  CHAMP_ADAPTIVE_DSW_GAME_SOL_STACKCAR
  CHAMP_ADAPTIVE_DSW_GAME_SOL_NONCOOP
)

if [ -n "${ARMS:-}" ]; then
  read -ra LIST <<< "${ARMS//,/ }"
elif [ "${FULL:-0}" = "1" ]; then
  LIST=("CHAMP_NO_TSP" "${ALL_ARMS[@]}")
else
  LIST=("CHAMP_NO_TSP" CHAMP_ADAPTIVE_DSW_GAME_COOP \
        CHAMP_ADAPTIVE_DSW_GAME_SOL_NASH CHAMP_ADAPTIVE_DSW_GAME_SOL_UTIL)
fi

if [ -n "${SEEDS:-}" ]; then
  read -ra SEEDL <<< "${SEEDS//,/ }"
elif [ "${FULL:-0}" = "1" ]; then
  SEEDL=(300 400 500)
else
  SEEDL=(300)
fi

# THE JOB BODY. Everything before BODY is per-job and baked; the body is written
# from a quoted heredoc so none of its ${...} is expanded at generation time.
emit_job () {
  local arm="$1" seed="$2" short="$3" out="$4"
  {
    cat <<HDR
#!/bin/bash
#PBS -N gs_${short}_${seed}
#PBS -l select=1:ncpus=4:mem=16gb
#PBS -l walltime=01:00:00
#PBS -j oe
#PBS -m be
#
# GENERATED by qb_gamesol_gen.sh -- do not edit; regenerate instead.
# Parameters are baked literals: no -v, nothing to drop.
CORR=${CORR}
ARM=${arm}
SEED=${seed}
END=${END}
HDR
    cat <<'BODY'

if [ -z "${BASE:-}" ]; then
  if [ -d /home/ahernz/tsp/sumo_hpc/sumo_bridge ]; then
    BASE=/home/ahernz/tsp/sumo_hpc
  else
    BASE=/scratch/ki13/za6261/tsp/sumo_hpc
  fi
fi
export BASE
cd "$BASE/sumo_bridge" || exit 1

if [ -z "${VENV:-}" ]; then
  if [ -f "$BASE/venv-gadi/bin/activate" ]; then
    VENV="$BASE/venv-gadi"
  else
    VENV="$BASE/venv"
  fi
fi
export VENV
source "$VENV/bin/activate"
_GADI_SUMO=/scratch/ki13/za6261/sumo-gadi
if [ -x "$_GADI_SUMO/bin/sumo" ]; then
    export SUMO_HOME="$_GADI_SUMO/share/sumo"
    export PATH="$_GADI_SUMO/bin:$PATH"
else
    export SUMO_HOME=${VENV:-$BASE/venv-gadi}/lib/python3.12/site-packages/sumo
    export PATH=$SUMO_HOME/bin:$PATH
fi
unset _GADI_SUMO
export PYTHONUTF8=1
export MPLBACKEND=Agg

# Baked values. Anything empty here means the generator wrote a bad file, so the
# job fails immediately and loudly instead of simulating a default search.
: "${ARM:?empty ARM in generated script - regenerate with qb_gamesol_gen.sh}"
: "${SEED:?empty SEED in generated script - regenerate with qb_gamesol_gen.sh}"
: "${CORR:?empty CORR in generated script - regenerate with qb_gamesol_gen.sh}"
END="${END:-4500}"

case "$ARM" in
  CHAMP_*) : ;;
  *) echo "!! ARM does not look like a champion arm: [$ARM]"; exit 1 ;;
esac
case "$SEED" in
  ''|*[!0-9]*) echo "!! SEED is not an integer: [$SEED]"; exit 1 ;;
esac

if [ "$CORR" = "kg" ]; then
  SCEN=kg_scenario
else
  CORR=logan_road_new
  SCEN=logan_scenario_realtls
fi
export CORRIDOR=$CORR

SHORT=${ARM#CHAMP_ADAPTIVE_DSW_}
OUT="$BASE/parts/gamesol_${SHORT}_eval${SEED}.csv"
mkdir -p "$BASE/parts"

echo "== $(hostname) $(date) arm=$ARM seed=$SEED corr=$CORR scen=$SCEN end=$END =="
echo "   (baked: no -v was used to get these values)"
grep -m1 '^ENGINE_BUILD' "$BASE/shared_tsp_engine/engine.py"
grep -m1 '^GAME_SOLUTION' "$BASE/shared_tsp_engine/specialized_modes.py"
echo "   -> $OUT"

python run_sweep_hpc.py --corridor "$CORR" --scenario "$SCEN" \
    --arms "$ARM" --seeds "$SEED" --skip-train --eval-seeds "$SEED" \
    --end "$END" --jobs 1 --keep-qtables --resume --out "$OUT" \
    || { echo "!! eval FAILED arm=$ARM seed=$SEED"; exit 1; }

echo "== rows =="
python - "$OUT" <<'PY'
import csv, sys
rows = list(csv.DictReader(open(sys.argv[1], encoding="utf-8")))
for r in rows:
    print("  %-34s seed=%s phase=%s ok=%s obj=%s paxh=%s"
          % (r.get("arm"), r.get("seed"), r.get("phase"), r.get("ok"),
             r.get("obj_pax_per_delay_hr"), r.get("avg_total_pass_delay_per_hr")))
print("  %d row(s)" % len(rows))
PY
echo "== done $(date) =="
BODY
  } > "$out"
}

echo "corridor=$CORR end=$END arms=${#LIST[@]} seeds=${SEEDL[*]} gen=$GEN"
N=0
for a in "${LIST[@]}"; do
  short=${a#CHAMP_ADAPTIVE_DSW_}
  for s in "${SEEDL[@]}"; do
    pbs="$GEN/qb_gamesol_${short}_${s}.pbs"
    emit_job "$a" "$s" "$short" "$pbs" || { echo "!! could not write $pbs"; exit 1; }
    # Read the baked values straight back out of the file we just wrote: this is
    # the check the old -v path could not give us.
    got_arm=$(sed -n 's/^ARM=//p' "$pbs" | head -1)
    got_seed=$(sed -n 's/^SEED=//p' "$pbs" | head -1)
    got_corr=$(sed -n 's/^CORR=//p' "$pbs" | head -1)
    if [ "$got_arm" != "$a" ] || [ "$got_seed" != "$s" ] || [ "$got_corr" != "$CORR" ]; then
      echo "!! baked-value mismatch in $pbs (arm=[$got_arm] seed=[$got_seed] corr=[$got_corr])"
      exit 1
    fi
    if [ "${DRY:-0}" = "1" ]; then
      echo "  [dry] $pbs  arm=$got_arm seed=$got_seed corr=$got_corr"
    else
      out=$(qsub -P "$RPID" "$pbs" 2>&1)
      echo "  $s $a -> $out"
      case "$out" in
        *[0-9].aqua*) : ;;
        *) echo "!! qsub rejected $pbs: $out"; exit 1 ;;
      esac
    fi
    N=$((N + 1))
  done
done
echo "$N job(s) written to $GEN"
[ "${DRY:-0}" = "1" ] || echo "watch:  qstat -u ahernz | grep gs_"
echo "score:  python _sumo_port/compare_game_solution.py --seeds ${SEEDL[*]}   (locally, on Windows)"
