"""check_ctm_cap_requirement.py -- fail a run that would truncate CTM approaches.

The two-class CTM clamps each approach to

    n_cells = max(1, min(ceil(L / cell_len), max_cells))      ctm_twoclass

so with max_cells too small the modelled domain is SHORTER than the plant
section and every vehicle beyond it is invisible to the payoff. This gate
recomputes the requirement from the measured geometry (ctm_approach_reach.csv,
generated by measure_ctm_reach.py) and fails if a configured cap is below it.

Requirement per corridor = max ceil(length_m / cell_len_m) over its measured
approach sections: 24 on KG (section 21546, 263.2 m at 11.1 m/cell), <= 12 on
Logan. It is recomputed from the CSV, never hard-coded, so a rebuilt model
raises it automatically.

Checked, per corridor:
  * run_config.py CBQL_CTM_MAX_CELLS and GAME_CTM2_LIGHTSIM_MAX_CELLS -- an
    ABSENT key is checked at the engine default of 12, because that is what the
    engine will actually use (globals().get(NAME, 12));
  * every arm in champion_search.py that pins either cap below the requirement,
    unless the arm is a DECLARED_CONTROLS entry (the deliberate old-behaviour
    arm used by the cap A/B).

    python -I check_ctm_cap_requirement.py                 # both corridors
    python -I check_ctm_cap_requirement.py --corridor kg
    python -I check_ctm_cap_requirement.py --arms A,B      # only an arm list

Exit 0 = every configured cap models the whole approach; 1 = at least one
truncates (details printed). Usable as a preflight gate; pipeline_preflight.py
runs it as its [C] section.
"""
from __future__ import print_function

import argparse
import ast
import csv
import math
import os
import sys
import types

HERE = os.path.dirname(os.path.abspath(__file__))
REACH_CSV = os.path.join(HERE, 'ctm_approach_reach.csv')
CHAMP = os.path.join(HERE, 'champion_search.py')
CORRIDORS = (('kg', 'kg'), ('logan_road_new', 'logan_road_new'))

CAP = 'CBQL_CTM_MAX_CELLS'
LI_CAP = 'GAME_CTM2_LIGHTSIM_MAX_CELLS'
CAPS = (CAP, LI_CAP)
ENGINE_DEFAULT = 12          # globals().get(NAME, 12) in engine.py

# Arms that deliberately reproduce the pre-2026-11-09 truncated behaviour, so
# the cap A/B has a control. They are reported, not failed.
DECLARED_CONTROLS = {
    'CHAMP_ADAPTIVE_DSW_GAME_SOL_NASH_CTM2_SPILL2_LIGHTSIM_CAP12':
        'cap A/B control: re-runs the old 12-cell truncation on purpose',
}


def asc(s):
    return ''.join(c if ord(c) < 128 else '?' for c in str(s))


def requirement(reach_csv=REACH_CSV):
    """{corridor: {'req': int, 'n': int, 'hard': [(need, jct, sec, L, cell)]}}"""
    out = {}
    with open(reach_csv, newline='', encoding='utf-8-sig') as fh:
        for r in csv.DictReader(fh):
            try:
                length = float(r['length_m'])
                cell = float(r['cell_len_m'])
            except (KeyError, TypeError, ValueError):
                continue
            if length <= 0 or cell <= 0:
                continue          # zero-length rows are an ANG failure, not geometry
            # EXACTLY ctm_twoclass.ApproachGeom's formula
            need = int(math.ceil(max(length, 1.0) / cell))
            cor = (r.get('corridor') or '?').strip()
            d = out.setdefault(cor, {'req': 0, 'n': 0, 'hard': []})
            d['n'] += 1
            d['hard'].append((need, r.get('junction'), r.get('section'), length, cell))
            d['req'] = max(d['req'], need)
    for d in out.values():
        d['hard'].sort(reverse=True)
    return out


def run_config_caps(cdir):
    """{key: value-or-None} from that corridor's run_config.py (no Aimsun)."""
    path = os.path.join(HERE, cdir, 'run_config.py')
    ns = types.ModuleType('run_config_' + cdir)
    with open(path, encoding='utf-8-sig') as fh:
        exec(compile(fh.read(), path, 'exec'), ns.__dict__)
    return {k: ns.__dict__.get(k) for k in CAPS}


def _consts(tree):
    out = {}
    for node in tree.body:
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)
                and isinstance(node.value, ast.Constant)
                and isinstance(node.value.value, str)):
            out[node.targets[0].id] = node.value.value
    return out


def _str(node, consts):
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.Name):
        return consts.get(node.id)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left, right = _str(node.left, consts), _str(node.right, consts)
        if left is not None and right is not None:
            return left + right
    return None


def arm_cap_pins(champ=CHAMP):
    """{arm_name: {cap_key: value}} for literal cap overrides in champion_search."""
    with open(champ, encoding='utf-8-sig') as fh:
        tree = ast.parse(fh.read())
    consts = _consts(tree)
    out = {}
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call)
                and isinstance(node.func, ast.Name)
                and node.func.id == '_with_overrides'
                and len(node.args) >= 3):
            continue
        name = _str(node.args[1], consts)
        if not name:
            continue
        try:
            extra = ast.literal_eval(node.args[2])
        except Exception:
            continue                      # **spread / computed dict
        if not isinstance(extra, dict):
            continue
        pins = {k: extra[k] for k in CAPS if k in extra}
        if pins:
            out[name] = pins
    return out


def run(corridors=None, arms=None, reach_csv=REACH_CSV, out=print):
    """Check the caps. Returns the number of failures (0 = pass)."""
    req = requirement(reach_csv)
    pins = arm_cap_pins()
    if arms:
        wanted = {a.strip() for a in arms if a.strip()}
        pins = {k: v for k, v in pins.items() if k in wanted}
        missing = sorted(wanted - set(pins))
    else:
        missing = []
    picked = [c for c in CORRIDORS if not corridors or c[0] in corridors]
    failures = 0

    out('CTM cell-cap requirement (from %s)' % os.path.basename(reach_csv))
    for name, cdir in picked:
        d = req.get(cdir)
        if not d:
            out('  [FAIL] %-14s no measured sections for this corridor in the CSV'
                % cdir)
            failures += 1
            continue
        need = d['req']
        out('  %-14s requirement %2d cells over %d approach sections '
            '(cell_len from the model calibration)' % (cdir, need, d['n']))
        for n, jct, sec, L, cell in d['hard'][:3]:
            if n >= need:
                out('      worst: junction %-8s section %-8s %6.1f m / %.1f m = %d cells'
                    % (jct, sec, L, cell, n))

        cfg = run_config_caps(cdir)
        for key in CAPS:
            val = cfg.get(key)
            eff = ENGINE_DEFAULT if val is None else int(val)
            tag = 'ABSENT (engine default %d)' % ENGINE_DEFAULT if val is None \
                else str(val)
            if eff < need:
                out('    [FAIL] %s = %s < %d -> approaches longer than '
                    '%d cells are TRUNCATED' % (key, tag, need, eff))
                failures += 1
            else:
                out('    [ok]   %s = %s' % (key, tag))

    if pins:
        out('  arms pinning a cap:')
        for name in sorted(pins):
            for key, val in sorted(pins[name].items()):
                if val >= max((req.get(c[1], {}).get('req', 0) for c in picked),
                              default=0):
                    out('    [ok]   %s.%s = %d' % (name, key, val))
                    continue
                if name in DECLARED_CONTROLS:
                    out('    [note] %s.%s = %d -- DECLARED CONTROL (%s)'
                        % (name, key, val, DECLARED_CONTROLS[name]))
                    continue
                out('    [FAIL] %s.%s = %d is below the requirement'
                    % (name, key, val))
                failures += 1
    else:
        out('  arms pinning a cap: none')
    if missing:
        out('  [note] %d requested arm(s) not found in champion_search: %s'
            % (len(missing), ', '.join(missing)))

    out('')
    out('%s (%d failure(s))' % ('PASS' if not failures else 'FAIL', failures))
    return failures


def main(argv=None):
    ap = argparse.ArgumentParser(
        description='Fail if a configured CTM cell cap truncates an approach.')
    ap.add_argument('--corridor', action='append', choices=[c[0] for c in CORRIDORS],
                    help='limit to one corridor (default: both)')
    ap.add_argument('--arms', default='',
                    help='comma-separated arm names the run will use')
    ap.add_argument('--reach-csv', default=REACH_CSV)
    a = ap.parse_args(argv)
    arms = [x for x in a.arms.split(',') if x.strip()]
    return 1 if run(a.corridor, arms, a.reach_csv) else 0


if __name__ == '__main__':
    sys.exit(main())
