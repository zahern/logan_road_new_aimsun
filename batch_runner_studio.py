                        strategy=no_tsp_p["strategy"],
                        coordinated=no_tsp_p["coordinated"],
                        coordination_algo=no_tsp_p["coordination_algo"],
                        reward_overrides={"BUS_OCC_OVERRIDE": float(bus)},
                        method_overrides={},
                        method=no_tsp_p.get("method", "NO_TSP"),
