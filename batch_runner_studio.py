def _overrides_to_text(ov: dict) -> str:
    return "\n".join(f"{k} = {v!r}" for k, v in ov.items())


def _text_to_overrides(text: str) -> dict:
    out = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            raise ValueError(f"override line has no '=': {line!r}")
        key, _, val = line.partition("=")
        key = key.strip()
        val = val.strip()
        try:
            out[key] = ast.literal_eval(val)
        except (ValueError, SyntaxError):
            out[key] = val  # keep as raw string (e.g. LSTM_SS)
    return out


def _unique_name(base: str, taken) -> str:
    sanitized_base = builder._sanitize_name(base)
    name, n = sanitized_base, 2
    while name in taken:
        name = f"{sanitized_base}_{n}"
        n += 1
    return name


def _make_experiment(name: str, strategy: str, coordinated: bool,
                     coordination_algo: str, reward_overrides: dict,
                     method_overrides=None, method: str = "",
                     active_intersections=None, enabled: bool = True) -> dict:
    uid = st.session_state._next_uid
    st.session_state._next_uid += 1
    return {
        "name": name, "enabled": enabled,
        "_uid": uid, "method": method,
        "strategy": strategy,
        "coordinated": coordinated,
        "coordination_algo": coordination_algo,
        "active_intersections": active_intersections,
        "reward_overrides": dict(reward_overrides),
        "method_overrides": dict(method_overrides or {}),
    }


def _newest(pattern: str):
    hits = glob.glob(pattern)
    return max(hits, key=os.path.getmtime) if hits else None


def _tail(path: str, n_lines: int = 40) -> str:
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            return "".join(f.readlines()[-n_lines:])
    except OSError as e:
        return f"(cannot read {path}: {e})"


def _load_results(csv_path: str):
    if pd is None or not os.path.isfile(csv_path):
        return None
    try:
        return pd.read_csv(csv_path)
    except Exception as e:
        st.error(f"Could not parse {os.path.basename(csv_path)}: {e}")
        return None


