    st.dataframe(df[id_cols + kpis], width='stretch')

    # ── Baseline deltas ──────────────────────────────────────────────────────
    if "run_experiment" in df.columns and kpis:
        st.subheader("Delta vs baseline")
        d = df.copy()
        demand_vals = sorted(d["run_demand_scalar"].dropna().unique().tolist()) \
            if "run_demand_scalar" in d.columns else []
        seed_vals = sorted(d["run_seed"].dropna().unique().tolist()) \
            if "run_seed" in d.columns else []
        f1, f2, f3 = st.columns(3)
        sel_demands = (f1.multiselect("Demand scalars (compare at same value)",
                                      demand_vals, default=demand_vals)
                       if demand_vals else [])
        sel_seeds = (f2.multiselect("Seeds", seed_vals, default=seed_vals)
                     if seed_vals else [])
        sel_regimes = f3.multiselect(
            "Regime / bus value (name filter)",
            ["PRO_BUS", "BALANCED", "PRO_CAR", "NO_TSP"],
            default=["PRO_BUS", "BALANCED", "PRO_CAR", "NO_TSP"],
            help="Filters experiments by a token in the experiment name — "
                 "e.g. pick PRO_BUS to compare strategies at the same bus value.")

        if sel_demands:
            d = d[d["run_demand_scalar"].isin(sel_demands)]
        if sel_seeds:
            d = d[d["run_seed"].isin(sel_seeds)]
        if sel_regimes:
            d = d[d["run_experiment"].astype(str).apply(
                lambda n: any(r in n.upper() for r in sel_regimes))]
        if d.empty:
            st.info("No runs match the current filters.")
        else:
            experiments = sorted(d["run_experiment"].astype(str).unique())
            default_base = next(
                (e for e in experiments if "NO_TSP" in e.upper()),
                experiments[0])
            baseline = st.selectbox("Baseline experiment", experiments,
                                    index=experiments.index(default_base))
            kpi = st.selectbox("KPI", kpis)
            show_per_seed = st.checkbox(
                "Show per-seed rows (don't average seeds)", value=False)
            try:
                keys = [k for k in ("run_seed", "run_demand_scalar") if k in d.columns]
                base = (d[d["run_experiment"].astype(str) == baseline]
                        .groupby(keys)[kpi].mean().rename("baseline"))
                merged = d.join(base, on=keys)
                merged["delta"] = merged[kpi].astype(float) - merged["baseline"].astype(float)
                group_cols = ["run_experiment"]
                if "run_demand_scalar" in merged.columns:
                    group_cols.append("run_demand_scalar")
                if show_per_seed and "run_seed" in merged.columns:
                    group_cols.append("run_seed")
                summary = (merged.groupby(group_cols)
                           .agg(mean_value=(kpi, "mean"), mean_delta=("delta", "mean"),
                                n_runs=(kpi, "size"))
                           .round(2))
                st.dataframe(summary, width='stretch')
                chart = summary["mean_delta"].copy()
                if isinstance(chart.index, pd.MultiIndex):
                    chart = chart[chart.index.get_level_values(0) != baseline]
                else:
                    chart = chart.drop(labels=[baseline], errors="ignore")
                st.bar_chart(chart)
            except Exception as e:
                st.warning(f"Could not compute deltas for {kpi}: {e}")

