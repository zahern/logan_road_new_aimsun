                            strategy=p["strategy"],
                            coordinated=p["coordinated"],
                            coordination_algo=p["coordination_algo"],
                            reward_overrides=dict(p.get("reward_overrides") or {}),
                            method_overrides=mo,
                            method=p.get("method", test_method),
