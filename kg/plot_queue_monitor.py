def _parse_folder(folder_name):
    """Extract strategy and seed from folder names."""
    parts = folder_name.split('_')
    for i, p in enumerate(parts):
        if p.lower().startswith('seed') and len(p) > 4:
            try:
                seed     = int(p[4:])
                strategy = '_'.join(parts[:i])
                return strategy, seed
            except ValueError:
                pass
    return None, None


def load_section_counts(results_root):
    """
    Load section_counts_*.csv files from each run folder.
    These files contain cumulative vehicle counts at detectors,
    which we can use to estimate queue lengths.
    """
    all_data = []
    
    for folder in os.listdir(results_root):
        fp = os.path.join(results_root, folder)
        if not os.path.isdir(fp):
            continue
            
        strategy, seed = _parse_folder(folder)
        if strategy is None:
            continue
            
        # Look for section counts files (generated by Simulation_Stats.py)
        section_files = glob.glob(os.path.join(fp, "section_counts_*.csv"))
        if not section_files:
            continue
            
        for sf in section_files:
            try:
                df = pd.read_csv(sf)
                # Add metadata
                df['_strategy'] = strategy
                df['_seed'] = seed
                df['_folder'] = folder
                all_data.append(df)
            except Exception as e:
                print(f"[QUEUE] WARNING: {sf}: {e}")
    
    return pd.concat(all_data, ignore_index=True) if all_data else pd.DataFrame()


