def plot_queue_timeseries(df_queue, strategy, seed, out_dir):
    """
    Plot queue length over time for all intersections.
    Creates a grid of subplots, one per intersection.
    """
    if df_queue.empty:
        return
    
    intersections = sorted(df_queue['intersection_id'].unique())
    n_inter = len(intersections)
    
    if n_inter == 0:
        return
    
    # Create subplot grid (max 4 columns)
    ncols = min(4, n_inter)
    nrows = (n_inter + ncols - 1) // ncols
    
    fig, axes = plt.subplots(nrows, ncols, figsize=(5 * ncols, 3.5 * nrows))
    axes = axes.flatten() if n_inter > 1 else [axes]
    
    for idx, jct_id in enumerate(intersections):
        ax = axes[idx]
        jct_data = df_queue[df_queue['intersection_id'] == jct_id]
        
        if jct_data.empty:
            ax.set_visible(False)
            continue
        
        # Plot queue length over time
        times = jct_data['time'].values
        queues = jct_data['queue_length'].values
        
        ax.plot(times, queues, color=STRATEGY_COLOURS.get(strategy, DEFAULT_COLOUR),
                linewidth=1.5, label=f'{strategy} (seed {seed})')
        
        # Add 60-second interval markers
        for t in range(0, int(times.max()) + 1, INTERVAL_S):
            ax.axvline(x=t, color='gray', linestyle='--', alpha=0.3, linewidth=0.5)
        
        ax.set_title(f'Jct {jct_id}', fontsize=9, fontweight='bold')
        ax.set_xlabel('Time (s)', fontsize=8)
        ax.set_ylabel('Queue (veh)', fontsize=8)
        ax.legend(fontsize=7, loc='upper left')
        ax.grid(True, alpha=0.3)
        ax.set_axisbelow(True)
    
    # Hide unused subplots
    for idx in range(n_inter, len(axes)):
        axes[idx].set_visible(False)
    
    fig.suptitle(f'Queue Length Monitor — {strategy} (Seed {seed})',
                 fontsize=12, fontweight='bold', y=1.02)
    plt.tight_layout()
    
    safe_name = f"{strategy}_seed{seed}".replace('/', '_')
    out_path = os.path.join(out_dir, f"queue_timeseries_{safe_name}.png")
    plt.savefig(out_path, dpi=150, bbox_inches='tight')
    plt.close(fig)
    print(f"[QUEUE] Saved: {out_path}")


def plot_queue_comparison(df_queue, out_dir):
    """
    Compare queue lengths across strategies at 60-second snapshots.
    Shows mean queue length at each snapshot time.
    """
    if df_queue.empty:
        return
    
    strategies = df_queue['_strategy'].unique()
    if len(strategies) == 0:
        return
    
    # Create time bins (60-second intervals)
    df_queue['time_bin'] = (df_queue['time'] // INTERVAL_S) * INTERVAL_S
    
    # Calculate mean queue per strategy per time bin
    fig, axes = plt.subplots(2, 1, figsize=(14, 10))
    
    # Top plot: Mean queue length over time
    ax1 = axes[0]
    for strategy in strategies:
        s_data = df_queue[df_queue['_strategy'] == strategy]
        if s_data.empty:
            continue
        
        mean_queue = s_data.groupby('time_bin')['queue_length'].mean()
        std_queue = s_data.groupby('time_bin')['queue_length'].std().fillna(0)
        
        times = mean_queue.index
        means = mean_queue.values
        stds = std_queue.values
        
        color = STRATEGY_COLOURS.get(strategy, DEFAULT_COLOUR)
        ax1.plot(times, means, color=color, linewidth=2, label=strategy)
        ax1.fill_between(times, means - stds, means + stds,
                        alpha=0.2, color=color)
    
    ax1.set_title('Mean Queue Length Over Time (All Intersections)',
                   fontsize=12, fontweight='bold')
    ax1.set_xlabel('Time (s)', fontsize=10)
    ax1.set_ylabel('Mean Queue Length (veh)', fontsize=10)
    ax1.legend(fontsize=9)
    ax1.grid(True, alpha=0.3)
    ax1.set_axisbelow(True)
    
    # Bottom plot: Queue length distribution at key snapshots
    ax2 = axes[1]
    snapshot_times = [0, 900, 1800, 2700, 3600]  # Every 15 minutes
    snapshot_times = [t for t in snapshot_times if t <= df_queue['time_bin'].max()]
    
    x = np.arange(len(snapshot_times))
    width = 0.8 / len(strategies)
    
    for si, strategy in enumerate(strategies):
        s_data = df_queue[df_queue['_strategy'] == strategy]
        if s_data.empty:
            continue
        
        means_at_snapshots = []
        for t in snapshot_times:
            bin_data = s_data[s_data['time_bin'] == t]
            mean_q = bin_data['queue_length'].mean() if not bin_data.empty else 0
            means_at_snapshots.append(mean_q)
        
        offset = (si - len(strategies) / 2.0 + 0.5) * width
        color = STRATEGY_COLOURS.get(strategy, DEFAULT_COLOUR)
        ax2.bar(x + offset, means_at_snapshots, width, label=strategy,
               color=color, edgecolor='white', linewidth=0.5)
    
    ax2.set_title(f'Queue Length at {INTERVAL_S}-Second Snapshots',
                   fontsize=12, fontweight='bold')
    ax2.set_xlabel('Snapshot Time (s)', fontsize=10)
    ax2.set_ylabel('Mean Queue Length (veh)', fontsize=10)
    ax2.set_xticks(x)
    ax2.set_xticklabels([f'{t}s' for t in snapshot_times], fontsize=9)
    ax2.legend(fontsize=9)
    ax2.grid(True, alpha=0.3, axis='y')
    ax2.set_axisbelow(True)
    
    plt.tight_layout()
    out_path = os.path.join(out_dir, "queue_comparison_all_strategies.png")
    plt.savefig(out_path, dpi=150, bbox_inches='tight')
    plt.close(fig)
    print(f"[QUEUE] Saved: {out_path}")


def plot_queue_heatmap(df_queue, out_dir):
    """
    Create a heatmap of queue lengths: time (rows) × intersection (columns).
    """
    if df_queue.empty:
        return
    
    # Pivot table: time_bin as rows, intersection_id as columns
    pivot = df_queue.pivot_table(
        index='time_bin',
        columns='intersection_id',
        values='queue_length',
        aggfunc='mean'
    )
    
    if pivot.empty:
        return
    
    # Plot heatmap
    fig, ax = plt.subplots(figsize=(12, 8))
    
    im = ax.imshow(pivot.values, aspect='auto', cmap='YlOrRd', interpolation='nearest')
    
    # Set labels
    ax.set_xticks(range(len(pivot.columns)))
    ax.set_xticklabels(pivot.columns, rotation=45, ha='right', fontsize=8)
    ax.set_yticks(range(len(pivot.index)))
    ax.set_yticklabels([f'{int(t)}s' for t in pivot.index], fontsize=8)
    
    # Colorbar
    cbar = plt.colorbar(im, ax=ax)
    cbar.set_label('Mean Queue Length (veh)', fontsize=10)
    
    ax.set_title('Queue Length Heatmap (Time × Intersection)',
                 fontsize=12, fontweight='bold')
    ax.set_xlabel('Intersection ID', fontsize=10)
    ax.set_ylabel('Time', fontsize=10)
    
    plt.tight_layout()
    out_path = os.path.join(out_dir, "queue_heatmap.png")
    plt.savefig(out_path, dpi=150, bbox_inches='tight')
    plt.close(fig)
    print(f"[QUEUE] Saved: {out_path}")


