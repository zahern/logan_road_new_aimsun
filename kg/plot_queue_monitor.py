def estimate_queue_from_detectors(section_df):
    """
    Estimate queue length from detector data.
    Queue = upstream count - downstream count (for each section).
    
    This assumes detectors at entry and exit of each link.
    """
    if section_df.empty:
        return pd.DataFrame()
    
    # Group by time and intersection
    queue_data = []
    
    # Required columns: time, section_id, upstream_count, downstream_count
    required_cols = ['time', 'section_id', 'upstream_count', 'downstream_count']
    if not all(col in section_df.columns for col in required_cols):
        print("[QUEUE] Missing required columns in section data")
        print(f"  Available: {list(section_df.columns)}")
        return pd.DataFrame()
    
    for (time, section_id), group in section_df.groupby(['time', 'section_id']):
        upstream = group['upstream_count'].sum()
        downstream = group['downstream_count'].sum()
        queue = max(0, upstream - downstream)
        queue_data.append({
            'time': time,
            'section_id': section_id,
            'queue_length': queue
        })
    
    return pd.DataFrame(queue_data)


