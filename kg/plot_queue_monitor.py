def main():
    print(f"[QUEUE] Queue Length Monitor")
    print(f"[QUEUE] Loading data from: {RESULTS_ROOT}")
    print(f"[QUEUE] Snapshot interval: {INTERVAL_S} seconds")
    
    os.makedirs(PLOTS_OUT, exist_ok=True)
    
    # Load section counts data
