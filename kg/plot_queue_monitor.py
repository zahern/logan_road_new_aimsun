def verify_bus_tracking(results_root):
    """
    Verify that bus tracking is working correctly by checking:
    1. Bus detection events are recorded
    2. Bus positions are tracked over time
    3. TSP actions (extensions/insertions) are logged
    """
    print("\n" + "=" * 80)
    print("BUS TRACKING VERIFICATION")
    print("=" * 80)
    
    bus_tracking_ok = True
    issues = []
    
    for folder in os.listdir(results_root):
        fp = os.path.join(results_root, folder)
        if not os.path.isdir(fp):
            continue
        
        strategy, seed = _parse_folder(folder)
        if strategy is None:
            continue
        
        # Check for bus detection files
        detection_files = glob.glob(os.path.join(fp, "*detection*.csv"))
        if not detection_files:
            issues.append(f"  {folder}: No bus detection files found")
            bus_tracking_ok = False
            continue
        
        # Check for TSP action logs
        tsp_files = glob.glob(os.path.join(fp, "*tsp*.csv"))
        if not tsp_files and strategy not in ["NORMAL"]:
            issues.append(f"  {folder}: No TSP action logs found")
            bus_tracking_ok = False
        
        # Check detection file contents
        for df in detection_files:
            try:
                df_data = pd.read_csv(df)
                if df_data.empty:
                    issues.append(f"  {folder}: Empty detection file: {os.path.basename(df)}")
                    bus_tracking_ok = False
                else:
                    # Check for required columns
                    required = ['bus_id', 'timestamp', 'intersection_id']
                    missing = [col for col in required if col not in df_data.columns]
                    if missing:
                        issues.append(f"  {folder}: Missing columns {missing} in detection file")
                        bus_tracking_ok = False
            except Exception as e:
                issues.append(f"  {folder}: Error reading {os.path.basename(df)}: {e}")
                bus_tracking_ok = False
    
    if bus_tracking_ok:
        print("✓ Bus tracking appears to be working correctly")
    else:
        print("✗ Bus tracking issues detected:")
        for issue in issues:
            print(issue)
    
    return bus_tracking_ok, issues


